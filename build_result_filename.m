function fname = build_result_filename(params, prefix)
%BUILD_RESULT_FILENAME Descriptive filename from simulation params.
    if nargin < 2, prefix = 'mono'; end
    fname = sprintf('%s_%s%d_pp%d_tgt%d_%dx%d_%dx%d_%s.mat', ...
        prefix, ...
        upper(params.modulation), params.ModOrder, ...
        params.pilot_power, ...
        params.n_targets, ...
        params.Nt, params.Nr, ...
        params.M, params.N, ...
        datestr(now, 'yyyymmdd_HHMM'));
end
