function fname = build_result_filename(params, prefix)
%BUILD_RESULT_FILENAME Descriptive filename from simulation params.
%   prefix defaults to params.config_name; the coarse method is tagged if params has one.
    if nargin < 2, prefix = params.config_name; end
    layout = 'blocks';
    if isempty(params.pilot_blocks_def), layout = 'random'; end
    method = '';
    if isfield(params, 'coarse_method'), method = [params.coarse_method '_']; end
    fname = sprintf('%s_%s_%s%s%d_pp%g_tgt%d_%dx%d_%dx%d_%s.mat', ...
        prefix, layout, method, ...
        upper(params.modulation), params.ModOrder, ...
        params.pilot_power, ...
        params.targets_num, ...
        params.Nt, params.Nr, ...
        params.M, params.N, ...
        datestr(now, 'yyyymmdd_HHMM'));
end
